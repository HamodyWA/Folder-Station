package com.example.data

data class FolderPreset(
    val id: String,
    val title: String,
    val subtitle: String,
    val columns: Int,
    val rows: Int,
    val shape: FolderEntity.ShapeType,
    val cornerRadiusDp: Int,
    val iconSizeDp: Int,
    val spacingDp: Int,
    val backgroundColorHex: String,
    val isGradient: Boolean,
    val gradientEndColorHex: String,
    val backgroundOpacity: Float,
    val borderColorHex: String,
    val borderThicknessDp: Int,
    val showTitle: Boolean,
    val showAppLabels: Boolean
) {
    fun toFolderEntity(customName: String? = null): FolderEntity {
        return FolderEntity(
            name = customName ?: title,
            columns = columns,
            rows = rows,
            shapeTypeFromPreset = shape,
            folderShape = shape.name,
            cornerRadiusDp = cornerRadiusDp,
            iconSizeDp = iconSizeDp,
            spacingDp = spacingDp,
            backgroundColorHex = backgroundColorHex,
            isGradient = isGradient,
            gradientEndColorHex = gradientEndColorHex,
            backgroundOpacity = backgroundOpacity,
            borderColorHex = borderColorHex,
            borderThicknessDp = borderThicknessDp,
            showTitle = showTitle,
            showAppLabels = showAppLabels
        )
    }

    private fun FolderEntity(
        name: String,
        columns: Int,
        rows: Int,
        shapeTypeFromPreset: FolderEntity.ShapeType,
        folderShape: String,
        cornerRadiusDp: Int,
        iconSizeDp: Int,
        spacingDp: Int,
        backgroundColorHex: String,
        isGradient: Boolean,
        gradientEndColorHex: String,
        backgroundOpacity: Float,
        borderColorHex: String,
        borderThicknessDp: Int,
        showTitle: Boolean,
        showAppLabels: Boolean
    ): FolderEntity {
        return FolderEntity(
            name = name,
            columns = columns,
            rows = rows,
            folderShape = folderShape,
            cornerRadiusDp = cornerRadiusDp,
            iconSizeDp = iconSizeDp,
            spacingDp = spacingDp,
            backgroundColorHex = backgroundColorHex,
            isGradient = isGradient,
            gradientEndColorHex = gradientEndColorHex,
            backgroundOpacity = backgroundOpacity,
            borderColorHex = borderColorHex,
            borderThicknessDp = borderThicknessDp,
            showTitle = showTitle,
            showAppLabels = showAppLabels
        )
    }
}

